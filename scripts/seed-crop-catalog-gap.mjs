async function main() {
  console.log('--- Ensuring Agricultural Master Crops in Database ---');
  let added = 0;
  let updated = 0;

  for (const crop of CROPS_TO_ENSURE) {
    const existing = await prisma.crop.findUnique({
      where: { slug: crop.slug },
      include: { translations: true },
    });

    if (!existing) {
      await prisma.crop.create({
        data: {
          slug: crop.slug,
          category: crop.category,
          scientificName: crop.scientificName,
          seasons: JSON.stringify(crop.seasons),
          typicalDurationDays: crop.typicalDurationDays,
          climate: crop.climate,
          soilSuitability: crop.soilSuitability,
          sowingPeriod: crop.sowingPeriod,
          irrigationGuidance: crop.irrigationGuidance,
          nutrientGuidance: crop.nutrientGuidance,
          commonWeeds: crop.commonWeeds,
          commonDiseases: crop.commonDiseases,
          commonPests: crop.commonPests,
          harvestGuidance: crop.harvestGuidance,
          storageGuidance: crop.storageGuidance,
          sourceAuthority: crop.sourceAuthority,
          displayColor: crop.displayColor,
          icon: crop.icon,
          status: 'published',
          translations: {
            create: [
              {
                locale: 'en',
                name: crop.en,
                aliases: JSON.stringify(crop.aliases.en),
                description: `${crop.en} (${crop.scientificName}) — ${crop.sowingPeriod}`,
              },
              {
                locale: 'gu',
                name: crop.gu,
                aliases: JSON.stringify(crop.aliases.gu),
                description: `${crop.en} (${crop.scientificName}) — ${crop.sowingPeriod}`,
              },
              {
                locale: 'hi',
                name: crop.hi,
                aliases: JSON.stringify(crop.aliases.hi),
                description: `${crop.en} (${crop.scientificName}) — ${crop.sowingPeriod}`,
              },
            ],
          },
        },
      });
      console.log(`+ Added crop: ${crop.en} (${crop.slug})`);
      added++;
    } else {
      // Ensure translations exist
      for (const loc of ['en', 'gu', 'hi']) {
        const tr = existing.translations.find((t) => t.locale === loc);
        const nameVal = loc === 'en' ? crop.en : loc === 'gu' ? crop.gu : crop.hi;
        const aliasesVal = crop.aliases[loc] || [];
        if (!tr) {
          await prisma.cropTranslation.create({
            data: {
              cropId: existing.id,
              locale: loc,
              name: nameVal,
              aliases: JSON.stringify(aliasesVal),
              description: `${crop.en} (${crop.scientificName})`,
            },
          });
          console.log(`  + Added ${loc} translation for ${crop.slug}`);
          updated++;
        }
      }
    }
  }

  console.log(`\nCompleted: ${added} added, ${updated} translations updated.`);
}

main()
  .catch((e) => {
    console.error('Seeding error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
