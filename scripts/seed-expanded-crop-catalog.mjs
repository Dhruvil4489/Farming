async function seedExpandedCrops() {
  console.log(`Starting expanded crop catalog seed (${ADDITIONAL_CROPS.length} crops)...`);
  const now = new Date();
  let created = 0;
  let updated = 0;

  for (const c of ADDITIONAL_CROPS) {
    const existing = await prisma.crop.findUnique({ where: { slug: c.slug } });

    const crop = await prisma.crop.upsert({
      where: { slug: c.slug },
      update: {
        category: c.category,
        scientificName: c.scientificName,
        seasons: JSON.stringify(c.seasons),
        typicalDurationDays: c.typicalDurationDays,
        climate: c.climate,
        soilSuitability: c.soilSuitability,
        sowingPeriod: c.sowingPeriod,
        irrigationGuidance: c.irrigationGuidance,
        nutrientGuidance: c.nutrientGuidance,
        commonWeeds: c.commonWeeds,
        commonDiseases: c.commonDiseases,
        commonPests: c.commonPests,
        harvestGuidance: c.harvestGuidance,
        storageGuidance: c.storageGuidance,
        sourceAuthority: c.sourceAuthority,
        lastVerifiedAt: now,
        displayColor: c.displayColor,
        status: 'published',
      },
      create: {
        slug: c.slug,
        category: c.category,
        scientificName: c.scientificName,
        seasons: JSON.stringify(c.seasons),
        typicalDurationDays: c.typicalDurationDays,
        climate: c.climate,
        soilSuitability: c.soilSuitability,
        sowingPeriod: c.sowingPeriod,
        irrigationGuidance: c.irrigationGuidance,
        nutrientGuidance: c.nutrientGuidance,
        commonWeeds: c.commonWeeds,
        commonDiseases: c.commonDiseases,
        commonPests: c.commonPests,
        harvestGuidance: c.harvestGuidance,
        storageGuidance: c.storageGuidance,
        sourceAuthority: c.sourceAuthority,
        lastVerifiedAt: now,
        displayColor: c.displayColor,
        status: 'published',
      },
    });

    if (existing) updated++;
    else created++;

    // Upsert EN / HI / GU translations with aliases
    const locales = [
      { locale: 'en', name: c.en, aliases: c.aliases.en || [] },
      { locale: 'hi', name: c.hi, aliases: c.aliases.hi || [] },
      { locale: 'gu', name: c.gu, aliases: c.aliases.gu || [] },
    ];
    for (const loc of locales) {
      await prisma.cropTranslation.upsert({
        where: { cropId_locale: { cropId: crop.id, locale: loc.locale } },
        update: {
          name: loc.name,
          aliases: JSON.stringify(loc.aliases),
          description: `${c.en} (${c.scientificName}) — ${c.sowingPeriod}`,
        },
        create: {
          cropId: crop.id,
          locale: loc.locale,
          name: loc.name,
          aliases: JSON.stringify(loc.aliases),
          description: `${c.en} (${c.scientificName}) — ${c.sowingPeriod}`,
        },
      });
    }

    // Seed varieties
    const existingVars = await prisma.cropVariety.findMany({ where: { cropId: crop.id } });
    const existingVarNames = new Set(existingVars.map((v) => v.name.toLowerCase()));
    for (const varName of c.varieties || []) {
      if (!existingVarNames.has(varName.toLowerCase())) {
        await prisma.cropVariety.create({
          data: {
            cropId: crop.id,
            name: varName,
            durationDays: c.typicalDurationDays,
            notes: `Recommended variety (${c.sourceAuthority})`,
            status: 'published',
          },
        });
      }
    }

    // Seed stages
    const stages = generateStagesForCrop(c);
    for (const st of stages) {
      const stage = await prisma.cropStage.upsert({
        where: { cropId_orderIndex: { cropId: crop.id, orderIndex: st.orderIndex } },
        update: {
          code: st.code,
          startOffsetDays: st.startOffsetDays,
          durationDays: st.durationDays,
          whatToDo: st.whatToDo,
          whyImportant: st.whyImportant,
          howToDo: st.howToDo,
          precautions: st.precautions,
          materials: st.materials,
          isEssential: st.isEssential ?? true,
          status: 'published',
        },
        create: {
          cropId: crop.id,
          orderIndex: st.orderIndex,
          code: st.code,
          startOffsetDays: st.startOffsetDays,
          durationDays: st.durationDays,
          whatToDo: st.whatToDo,
          whyImportant: st.whyImportant,
          howToDo: st.howToDo,
          precautions: st.precautions,
          materials: st.materials,
          isEssential: st.isEssential ?? true,
          status: 'published',
        },
      });

      await prisma.cropStageTranslation.upsert({
        where: { stageId_locale: { stageId: stage.id, locale: 'en' } },
        update: { name: st.name, description: st.whatToDo },
        create: { stageId: stage.id, locale: 'en', name: st.name, description: st.whatToDo },
      });
    }
  }

  const totalCrops = await prisma.crop.count();
  const totalStages = await prisma.cropStage.count();
  console.log(`✅ Success! Created ${created}, Updated ${updated}. DB Total Crops: ${totalCrops}, Stages: ${totalStages}`);
}

seedExpandedCrops()
  .catch((err) => {
    console.error('Seed failed:', err);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
